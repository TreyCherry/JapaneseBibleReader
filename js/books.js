const BY_CODE = new Map(BOOKS.map(([code, ja, en], i) => [code, { code, ja, en, index: i, testament: i < 39 ? 'OT' : 'NT' }]));

export function bookInfo(code) {
  return BY_CODE.get(code) || { code, ja: code, en: code, index: 999, testament: 'Other' };
}

export function chapterLabelJa(code, ch) {
  return code === 'Psa' ? `第${ch}編` : `${ch}章`;
}
